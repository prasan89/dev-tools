// Fictional social network data for dev-tools demos.
// All names, emails, and handles are invented; avatars are placeholder URLs.

export interface SocialUser {
  id: string;
  username: string;
  displayName: string;
  email: string;
  bio: string;
  avatar: string;
  followers: number;
  following: number;
  posts: number;
  verified: boolean;
  joinedAt: string;
  location: string;
  website: string;
}

export interface LocationObj {
  city: string;
  state: string;
  country: string;
  timezone: string;
}

export interface Education {
  institution: string;
  degree: string;
  field: string;
  startYear: number;
  endYear: number | null;
}

export interface Experience {
  company: string;
  role: string;
  startDate: string;
  endDate: string | null;
  current: boolean;
  description: string;
}

export interface Profile {
  id: string;
  userId: string;
  firstName: string;
  lastName: string;
  birthday: string;
  gender: string;
  location: LocationObj;
  interests: string[];
  skills: string[];
  education: Education[];
  experience: Experience[];
}

export interface SocialPost {
  id: string;
  userId: string;
  authorName: string;
  content: string;
  mediaType: null | "image" | "video";
  mediaUrl: string | null;
  likes: number;
  comments: number;
  shares: number;
  hashtags: string[];
  createdAt: string;
  visibility: "public" | "friends" | "private";
}

export interface Comment {
  id: string;
  postId: string;
  userId: string;
  authorName: string;
  content: string;
  likes: number;
  createdAt: string;
  parentId: string | null;
  replies: number;
}

export interface Like {
  id: string;
  userId: string;
  targetType: "post" | "comment";
  targetId: string;
  createdAt: string;
}

export interface FollowRelationship {
  id: string;
  followerId: string;
  followingId: string;
  createdAt: string;
  mutual: boolean;
}

export interface Message {
  id: string;
  conversationId: string;
  senderId: string;
  senderName: string;
  content: string;
  type: "text" | "image" | "link";
  read: boolean;
  createdAt: string;
}

export interface Actor {
  id: string;
  name: string;
  avatar: string;
}

export interface Notification {
  id: string;
  userId: string;
  type: "like" | "comment" | "follow" | "mention" | "system";
  title: string;
  message: string;
  read: boolean;
  createdAt: string;
  actionUrl: string;
  actor: Actor;
}

export interface Group {
  id: string;
  name: string;
  slug: string;
  description: string;
  category: string;
  members: number;
  posts: number;
  privacy: "public" | "private";
  createdBy: string;
  createdAt: string;
  tags: string[];
  avatar: string;
}

export interface Community {
  id: string;
  name: string;
  description: string;
  topic: string;
  members: number;
  moderators: string[];
  rules: string[];
  createdAt: string;
  active: boolean;
}

