// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface BankTransaction {
  id: string;
  accountId: string;
  date: string;
  description: string;
  category: string;
  amount: number;
  currency: string;
  type: 'debit' | 'credit';
  balance: number;
  merchant: string;
  reference: string;
}

export interface InvoiceItem {
  description: string;
  quantity: number;
  unitPrice: number;
  total: number;
}

export interface Invoice {
  id: string;
  invoiceNumber: string;
  clientName: string;
  clientEmail: string;
  items: InvoiceItem[];
  subtotal: number;
  taxRate: number;
  tax: number;
  total: number;
  status: 'draft' | 'sent' | 'paid' | 'overdue' | 'cancelled';
  issueDate: string;
  dueDate: string;
  paidDate: string | null;
}

export interface ExpenseRecord {
  id: string;
  date: string;
  description: string;
  category: string;
  amount: number;
  currency: string;
  paidBy: string;
  project: string;
  receipt: boolean;
  approved: boolean;
  tags: string[];
}

export interface Currency {
  code: string;
  name: string;
  symbol: string;
  country: string;
  type: 'fiat' | 'crypto';
  decimalPlaces: number;
  exchangeRate: number;
}

export interface StockDataPoint {
  date: string;
  open: number;
  high: number;
  low: number;
  close: number;
  volume: number;
}

export interface StockSample {
  ticker: string;
  company: string;
  dataPoints: StockDataPoint[];
}

export interface PaymentMethod {
  id: string;
  name: string;
  type: string;
  description: string;
  processingFee: number;
  settlementTime: string;
  countries: string[];
  popular: boolean;
}

export interface FinancialCategory {
  id: string;
  name: string;
  type: 'income' | 'expense' | 'both';
  icon: string;
  color: string;
  subcategories: string[];
}

export interface BudgetIncomeItem {
  source: string;
  amount: number;
}

export interface BudgetExpenseItem {
  category: string;
  budget: number;
  actual: number;
}

export interface Budget {
  id: string;
  name: string;
  month: number;
  year: number;
  income: BudgetIncomeItem[];
  expenses: BudgetExpenseItem[];
  totalIncome: number;
  totalBudget: number;
  totalActual: number;
  surplus: number;
}

export interface Account {
  id: string;
  accountNumber: string;
  type: 'checking' | 'savings' | 'credit' | 'investment';
  name: string;
  balance: number;
  currency: string;
  institution: string;
  openedDate: string;
  status: 'active' | 'inactive' | 'closed' | 'frozen';
}

