// ---------------------------------------------------------------------------
// Build indexes
// ---------------------------------------------------------------------------

const bySlug = new Map<string, Dataset>(DATASETS.map((d) => [d.slug, d]));
const byCategory = new Map<DatasetCategory, Dataset[]>();

for (const dataset of DATASETS) {
  const existing = byCategory.get(dataset.category) ?? [];
  existing.push(dataset);
  byCategory.set(dataset.category, existing);
}

const searchIndex = DATASETS.map((d) => ({
  dataset: d,
  tokens: [d.name, d.slug, d.description, d.category, ...(d.tags ?? [])].join(' ').toLowerCase(),
}));

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/** Returns metadata for all datasets (no data arrays) */
export function getDatasets(): DatasetMeta[] {
  return DATASETS.map(({ data: _data, ...meta }) => meta);
}

/** Returns a full Dataset (metadata + data) by slug */
export function getDatasetBySlug(slug: string): Dataset | undefined {
  return bySlug.get(slug);
}

/** Returns metadata for all datasets in a given category */
export function getDatasetsByCategory(cat: DatasetCategory): DatasetMeta[] {
  return (byCategory.get(cat) ?? []).map(({ data: _data, ...meta }) => meta);
}

/** Returns metadata for popular datasets, optionally limited */
export function getPopularDatasets(limit?: number): DatasetMeta[] {
  const popular = DATASETS.filter((d) => d.popular).map(({ data: _data, ...meta }) => meta);
  return limit !== undefined ? popular.slice(0, limit) : popular;
}

/** Full-text search across name, slug, description, category, and tags */
export function searchDatasets(query: string): DatasetMeta[] {
  const q = query.toLowerCase().trim();
  if (!q) return getDatasets();
  return searchIndex
    .filter(({ tokens }) => tokens.includes(q) || tokens.split(' ').some((tok) => tok.startsWith(q)))
    .map(({ dataset: { data: _data, ...meta } }) => meta);
}

